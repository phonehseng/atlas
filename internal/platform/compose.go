// ComposeFile / EnvFile are the Docker Compose project files.
func ComposeFile(st *core.Stack) string { return filepath.Join(st.Root, "docker-compose.yml") }
func EnvFile(st *core.Stack) string     { return filepath.Join(st.Root, ".env") }

// VPNSecrets are the VPN credentials, kept only in <root>/.env (readable by its owner only).
type VPNSecrets struct {
	User, Password, PrivateKey, Addresses string
}

// WriteVPNSecrets stores the VPN login for the Gluetun container.
func WriteVPNSecrets(st *core.Stack, s VPNSecrets) error {
	env := map[string]string{}
	if b, err := os.ReadFile(EnvFile(st)); err == nil {
		for _, line := range strings.Split(string(b), "\n") {
			if k, v, ok := strings.Cut(strings.TrimSpace(line), "="); ok && !strings.HasPrefix(k, "#") {
				env[k] = v
			}
		}
	}
	env["VPN_USER"], env["VPN_PASSWORD"] = quoteEnv(s.User), quoteEnv(s.Password)
	env["VPN_WIREGUARD_KEY"], env["VPN_WIREGUARD_ADDRESSES"] = quoteEnv(s.PrivateKey), quoteEnv(s.Addresses)
	var b strings.Builder
	b.WriteString("# Secrets for docker-compose.yml (written by Media Stack Setup). Keep this file private.\n")
	for _, k := range core.SortedKeys(env) {
		b.WriteString(k + "=" + env[k] + "\n")
	}
	if err := core.WriteFileAtomic(EnvFile(st), []byte(b.String()), 0o600); err != nil {
		return err
	}
	return Chown(st, EnvFile(st))
}

// quoteEnv single-quotes a value so Compose takes it literally ($, #, spaces).
func quoteEnv(v string) string {
	if v == "" {
		return ""
	}
	return "'" + strings.ReplaceAll(v, "'", `'"'"'`) + "'"
}

// WriteCompose regenerates docker-compose.yml from the installed apps.
func WriteCompose(st *core.Stack) error {
	doc, err := BuildCompose(st)
	if err != nil {
		return err
	}
	var b strings.Builder
	b.WriteString("# Generated by Media Stack Setup - re-running a setup step rewrites this file.\n")
	enc := yaml.NewEncoder(&b)
	enc.SetIndent(2)
	if err := enc.Encode(doc); err != nil {
		return err
	}
	if _, err := os.Stat(EnvFile(st)); os.IsNotExist(err) {
		if err := WriteVPNSecrets(st, VPNSecrets{}); err != nil {
			return err
		}
	}
	return core.WriteFileAtomic(ComposeFile(st), []byte(b.String()), 0o644)
}

// BuildCompose builds the Compose document (exported for tests).
func BuildCompose(st *core.Stack) (map[string]any, error) {
	services := map[string]any{}
	ids := st.DeployedApps()
	sort.Strings(ids)
	vpn := st.VPN.Mode == "gluetun"
	for _, id := range ids {
		a := Apps[id]
		if a == nil || a.Docker == nil {
			continue
		}
		s := service(st, a)
		if id == "qbittorrent" && vpn {
			// Torrent traffic can only leave through the VPN container: if the VPN drops, qBittorrent has
			// no network at all. Its Web UI is published by the VPN container instead.
			delete(s, "ports")
			s["network_mode"] = "service:gluetun"
			s["depends_on"] = map[string]any{"gluetun": map[string]any{"condition": "service_healthy"}}
		}
		if id == "gluetun" {
			gluetun(st, s)
		}
		services[id] = s
	}
	return map[string]any{
		"name":     Project(st),
		"services": services,
	}, nil
}

func service(st *core.Stack, a *App) map[string]any {
	spec := a.Docker
	s := map[string]any{"restart": "unless-stopped"}
	if spec.Build != "" {
		s["build"] = map[string]any{"context": filepath.ToSlash(filepath.Join(st.Root, spec.Build))}
		s["image"] = imageOf(st, a)
		s["pull_policy"] = "build"
	} else {
		s["image"] = spec.Image
	}
	env := map[string]any{"TZ": st.TZ}
	if spec.LSIO {
		env["PUID"], env["PGID"] = fmt.Sprint(st.UID), fmt.Sprint(st.GID)
	}
	for k, v := range spec.Env {
		env[k] = v
	}
	s["environment"] = env
	if spec.User {
		s["user"] = fmt.Sprintf("%d:%d", st.UID, st.GID)
	}
	var vols []string
	for _, v := range spec.Volumes {
		vols = append(vols, expandVolume(st, a.ID, v))
	}
	if len(vols) > 0 {
		s["volumes"] = vols
	}
	if spec.Port > 0 {
		bind := ""
		if spec.Local {
			bind = "127.0.0.1:"
		}
		s["ports"] = []string{fmt.Sprintf("%s%d:%d", bind, st.Port(a.ID), spec.Port)}
	}
	if len(spec.Command) > 0 {
		s["command"] = spec.Command
	}
	s["logging"] = map[string]any{"driver": "json-file", "options": map[string]any{"max-size": "10m", "max-file": "3"}}
	for k, v := range spec.Extra {
		s[k] = v
	}
	if a.ID == "jellyfin" {
		// Hardware video decoding/encoding (Intel/AMD) when the GPU device exists.
		if _, err := os.Stat("/dev/dri"); err == nil {
			s["devices"] = []string{"/dev/dri:/dev/dri"}
			if gid := renderGroup(); gid != "" {
				s["group_add"] = []string{gid}
			}
		}
	}
	if a.ID == "hub" {
		if gid := dockerGroup(); gid != "" {
			s["group_add"] = []string{gid}
		}
	}
	return s
}

func gluetun(st *core.Stack, s map[string]any) {
	env := s["environment"].(map[string]any)
	env["VPN_SERVICE_PROVIDER"] = st.VPN.Provider
	if st.Opt("vpn_type") == "wireguard" {
		env["VPN_TYPE"] = "wireguard"
		env["WIREGUARD_PRIVATE_KEY"] = "${VPN_WIREGUARD_KEY}"
		if st.Opt("vpn_wg_addresses") == "1" {
			env["WIREGUARD_ADDRESSES"] = "${VPN_WIREGUARD_ADDRESSES}"
		}
	} else {
		env["VPN_TYPE"] = "openvpn"
		env["OPENVPN_USER"] = "${VPN_USER}"
		env["OPENVPN_PASSWORD"] = "${VPN_PASSWORD}"
	}
	if st.VPN.Country != "" {
		env["SERVER_COUNTRIES"] = st.VPN.Country
	}
	s["cap_add"] = []string{"NET_ADMIN"}
	s["devices"] = []string{"/dev/net/tun:/dev/net/tun"}
	// qBittorrent's Web UI lives inside this container's network.
	s["ports"] = []string{fmt.Sprintf("%d:8080", st.Port("qbittorrent"))}
}

func expandVolume(st *core.Stack, id, v string) string {
	r := strings.NewReplacer("{config}", filepath.ToSlash(st.ConfigDir(id)), "{data}", filepath.ToSlash(st.DataDir()),
		"{root}", filepath.ToSlash(st.Root))
	return r.Replace(v)
}

func yamlMarshal(v any) ([]byte, error) { return yaml.Marshal(v) }
